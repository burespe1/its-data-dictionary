"""Check the term files and build the website sources and the Turtle file.

Usage:
    python scripts/build.py --check     # validate term files only (used on every pull request)
    python scripts/build.py             # validate, then write _site_src/ (for MkDocs) and itsdd.ttl

Environment variables:
    ITSDD_VERSION   release version written into the Turtle and the pages (default: "draft")
    ITSDD_BASE      URI namespace (default: a provisional example.org namespace, see docs/workflow.md)

Requires: PyYAML.
"""
import argparse
import os
import re
import shutil
import sys
from datetime import date
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
TERMS = ROOT / "terms"
OUT = ROOT / "_site_src"
REPO = "NAPCORE/its-data-dictionary"

STATUSES = ["proposed", "ready for review", "under review", "approved", "for thorough review", "archived"]
REQUIRED = ["id", "label", "status", "source"]

# folder -> (title, ELI of the legal act)
REGULATIONS = {
    "2024-490": ("MMTIS – Multimodal travel information services, DR (EU) 2017/1926 as amended by DR (EU) 2024/490",
                 "http://data.europa.eu/eli/reg_del/2024/490/oj"),
    "2022-670": ("RTTI – Real-time traffic information, DR (EU) 2022/670",
                 "http://data.europa.eu/eli/reg_del/2022/670/oj"),
    "886-2013": ("SRTI – Safety-related traffic information, DR (EU) 886/2013",
                 "http://data.europa.eu/eli/reg_del/2013/886/oj"),
    "885-2013": ("SSTP – Safe and secure truck parking, DR (EU) 885/2013",
                 "http://data.europa.eu/eli/reg_del/2013/885/oj"),
    "2023-1804": ("AFIR – Alternative fuels infrastructure, Regulation (EU) 2023/1804",
                  "http://data.europa.eu/eli/reg/2023/1804/oj"),
    "2026-253": ("TEL-TSI – Telematics applications for rail, Implementing Regulation (EU) 2026/253", None),
    "2015-962": ("RTTI (repealed) – DR (EU) 2015/962", "http://data.europa.eu/eli/reg_del/2015/962/oj"),
}

FRONT = re.compile(r"\A---\s*\n(.*?)\n---\s*\n?(.*)\Z", re.S)


def load():
    terms, errors, warnings = [], [], []
    for folder in sorted(p for p in TERMS.iterdir() if p.is_dir() and p.name in REGULATIONS):
        for f in sorted(folder.glob("*.md")):
            text = f.read_text(encoding="utf-8")
            m = FRONT.match(text)
            where = f.relative_to(ROOT).as_posix()
            if not m:
                errors.append(f"{where}: no YAML front matter")
                continue
            try:
                fm = yaml.safe_load(m.group(1)) or {}
            except yaml.YAMLError as e:
                errors.append(f"{where}: invalid YAML ({e.__class__.__name__})")
                continue
            for k in REQUIRED:
                if not fm.get(k):
                    errors.append(f"{where}: missing '{k}'")
            if not fm.get("definition"):
                msg = f"{where}: no definition"
                (errors if fm.get("status") == "approved" else warnings).append(msg)
            if fm.get("id") and fm["id"] != f.stem:
                errors.append(f"{where}: id '{fm['id']}' differs from the file name")
            if fm.get("status") and fm["status"] not in STATUSES:
                warnings.append(f"{where}: status '{fm['status']}' is not one of {', '.join(STATUSES)}")
            terms.append({"folder": folder.name, "fm": fm, "body": m.group(2).strip(), "path": where})
    ids = {}
    for t in terms:
        key = (t["folder"], t["fm"].get("id"))
        if key in ids:
            errors.append(f"{t['path']}: duplicate id, also in {ids[key]}")
        ids[key] = t["path"]
    return terms, errors, warnings


def esc(s):
    return str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def turtle(terms, base, version):
    lines = [
        "# ITS Data Dictionary – generated by scripts/build.py, do not edit.",
        "# PROVISIONAL URIs until the namespace is decided." if "example.org" in base else "",
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
        "@prefix dct: <http://purl.org/dc/terms/> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix r5r: <http://data.europa.eu/r5r/> .",
        "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
        "",
        f"<{base}> a skos:ConceptScheme ;",
        '    dct:title "NAPCORE ITS Data Dictionary"@en ;',
        f'    owl:versionInfo "{esc(version)}" ;',
        f'    dct:modified "{date.today().isoformat()}"^^xsd:date .',
        "",
    ]
    for t in terms:
        fm = t["fm"]
        uri = f"{base}{t['folder']}/{fm['id']}"
        pref = fm.get("short_name") or fm["label"]
        props = [f"skos:inScheme <{base}>", f'skos:prefLabel "{esc(pref)}"@en']
        if fm.get("short_name") and fm["label"] != fm["short_name"]:
            props.append(f'skos:altLabel "{esc(fm["label"])}"@en')
        if fm.get("definition"):
            props.append(f'skos:definition "{esc(fm["definition"])}"@en')
        eli = REGULATIONS[t["folder"]][1]
        if eli:
            props.append(f"r5r:applicableLegislation <{eli}>")
        for u in fm.get("mobility_theme") or []:
            if str(u).startswith("http"):
                props.append(f"skos:closeMatch <{u}>")
        for u in [fm.get("model")] if fm.get("model") else []:
            props.append(f"rdfs:seeAlso <{u}>")
        if fm.get("modified"):
            props.append(f'dct:modified "{fm["modified"]}"^^xsd:date')
        if fm.get("status") == "archived":
            props.append("owl:deprecated true")
        lines.append(f"<{uri}> a skos:Concept ;\n    " + " ;\n    ".join(props) + " .\n")
    return "\n".join(l for l in lines if l is not None)

URL = re.compile(r'(?<![(<"\]=])(https?://[^\s<>|)\]]+[^\s<>|)\].,;:])')


def normalize(body):
    """Make GitHub-flavoured term text render the same in MkDocs (Python-Markdown).

    - a table needs an empty line before it, also inside a > quote;
    - a backslash at the end of a line (hard line break) becomes two spaces;
    - bare URLs become links.
    """
    out, fence = [], False
    for line in body.splitlines():
        if line.lstrip("> ").startswith("```"):
            fence = not fence
        if not fence:
            m = re.match(r"^(>\s?)?", line)
            q, text = m.group(0), line[m.end():]
            prev = out[-1] if out else ""
            ptext = re.sub(r"^>\s?", "", prev)
            if text.lstrip().startswith("|") and ptext.strip() and not ptext.lstrip().startswith("|"):
                out.append(q.rstrip())
            if text.rstrip().endswith("\\") and not text.rstrip().endswith("\\\\"):
                line = line.rstrip()[:-1] + "  "
            if "`" not in line:
                line = URL.sub(r"<\1>", line)
        out.append(line)
    return "\n".join(out)


def page(t, version):
    fm = t["fm"]
    rows = [("ID", f"`{fm['id']}`"), ("Short name", fm.get("short_name", "")),
            ("Status", fm.get("status", "")), ("Regulation", REGULATIONS[t["folder"]][0]),
            ("Last revised", fm.get("modified", "—")),
            ("Relevant modes", ", ".join(fm.get("modes") or [])),
            ("mobilityDCAT-AP", ", ".join(f"<{u}>" for u in fm.get("mobility_theme") or [])),
            ("Detailed concept model", f"<{fm['model']}>" if fm.get("model") else "")]
    table = "| Field | Value |\n| --- | --- |\n" + "\n".join(f"| {k} | {v} |" for k, v in rows if v)
    definition = (f"!!! abstract \"Definition\"\n    {fm['definition']}\n\n"
                  if fm.get("definition") else "*No definition yet.*\n\n")
    return (f"# {fm['label']}\n\n{definition}{table}\n\n{normalize(t['body'])}\n\n---\n"
            f"*NAPCORE ITS Data Dictionary {version}. Select any text on this page to comment on it.*\n")


def build(terms, version):
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir()
    if (TERMS / "assets").exists():
        shutil.copytree(TERMS / "assets", OUT / "assets")
    if (ROOT / "docs-site").exists():  # site-wide files, e.g. js/comment.js
        shutil.copytree(ROOT / "docs-site", OUT, dirs_exist_ok=True)
    by_folder = {}
    for t in terms:
        by_folder.setdefault(t["folder"], []).append(t)
    home = [f"# NAPCORE ITS Data Dictionary\n\nVersion **{version}**, built {date.today().isoformat()}.\n",
            "Definitions of the data categories in the delegated regulations of the ITS Directive, "
            "AFIR and TEL-TSI. Select text on any page to comment on it.\n",
            "| Regulation | Terms |\n| --- | --- |"]
    for folder, items in by_folder.items():
        title = REGULATIONS[folder][0]
        home.append(f"| [{title}]({folder}/index.md) | {len(items)} |")
        lst = [f"# {title}\n", "| Term | Status | Last revised |\n| --- | --- | --- |"]
        for t in sorted(items, key=lambda x: x["fm"]["label"].lower()):
            fm = t["fm"]
            lst.append(f"| [{fm['label']}]({fm['id']}.md) | {fm.get('status', '')} | {fm.get('modified', '—')} |")
            (OUT / folder).mkdir(exist_ok=True)
            (OUT / folder / f"{fm['id']}.md").write_text(page(t, version), encoding="utf-8")
        (OUT / folder / "index.md").write_text("\n".join(lst) + "\n", encoding="utf-8")
    home.append("\nMachine-readable: [itsdd.ttl](itsdd.ttl)\n")
    (OUT / "index.md").write_text("\n".join(home), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="validate only")
    args = ap.parse_args()
    terms, errors, warnings = load()
    for w in warnings:
        print("warning:", w)
    for e in errors:
        print("error:", e)
    print(f"{len(terms)} term files, {len(errors)} errors, {len(warnings)} warnings")
    if errors:
        sys.exit(1)
    if args.check:
        return
    version = os.getenv("ITSDD_VERSION", "draft")
    base = os.getenv("ITSDD_BASE", "https://example.org/provisional/itsdd/")
    build(terms, version)
    (OUT / "itsdd.ttl").write_text(turtle(terms, base, version), encoding="utf-8")
    print(f"written {OUT.relative_to(ROOT)}/ and itsdd.ttl")


if __name__ == "__main__":
    main()
